export function textWidth(s: string, scale = 1): number {
  return s.length ? (s.length * 6 - 1) * scale : 0;
}

/** Draws text with a 1px drop shadow. `align` is relative to x. */
export function drawText(
  g: CanvasRenderingContext2D,
  s: string,
  x: number,
  y: number,
  color: string,
  scale = 1,
  align: "left" | "center" | "right" = "left",
  shadow: string | null = "rgba(0,0,0,0.85)",
): void {
  const w = textWidth(s, scale);
  let cx = Math.round(align === "center" ? x - w / 2 : align === "right" ? x - w : x);
  const cy = Math.round(y);
  const passes: Array<[string, number]> = shadow ? [[shadow, scale], [color, 0]] : [[color, 0]];
  for (const [col, off] of passes) {
    g.fillStyle = col;
    let px = cx + off;
    for (const ch of s) {
      const rows = G[ch] ?? G[ch.toUpperCase()] ?? G["?"]!;
      for (let r = 0; r < 7; r++) {
        const bits = rows[r]!;
        if (!bits) continue;
        for (let c = 0; c < 5; c++) if (bits & (16 >> c)) g.fillRect(px + c * scale, cy + off + r * scale, scale, scale);
      }
      px += 6 * scale;
    }
  }
  void cx;
}
